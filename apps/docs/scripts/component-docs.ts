import { dependencySections, installSection } from "@/app/(features)/agent-markdown/registry-sections";
import type { CompositionNode } from "@/app/(features)/catalog/compositions/types";
import type { ContractScope, ContractState } from "./skin-contract/model";

export const componentDocsDir = "src/registry/docs";

export function componentDocSource(id: string) {
  return `${componentDocsDir}/${id}.md`;
}

export function isComponentDocSource(source: string) {
  return source.startsWith(`${componentDocsDir}/`);
}

export type ComponentDocModule = { specifier: string; values: string[]; types: string[] };

export type ComponentDocInput = {
  id: string;
  name: string;
  summary: string;
  status?: string;
  pageUrl: string;
  install: string[];
  npmImportNote: string;
  dependencies: readonly string[];
  registryDependencies: readonly string[];
  modules: ComponentDocModule[];
  compositions: readonly { title: string; description?: string; tree: CompositionNode }[];
  example?: string;
  anatomy?: { selectorPattern: string; scopes: Record<string, ContractScope> };
  knobs: readonly { id: string; knobs: readonly { name: string; defaultValue: string }[] }[];
  contractUrls: string[];
};

const generatedHeader =
  "<!-- Generated by Control UI from its catalog and the installed source (apps/docs/scripts/gen-component-docs.ts). Do not edit: updating the component replaces this file. -->";

function fence(code: string, language: string) {
  const longestRun = Math.max(2, ...[...code.matchAll(/`+/g)].map((match) => match[0].length));
  const marker = "`".repeat(longestRun + 1);
  return `${marker}${language}\n${code.replace(/\n+$/, "")}\n${marker}`;
}

function compositionLines(node: CompositionNode, depth: number): string[] {
  const indent = "  ".repeat(depth);
  const children = node.children.flatMap((child) => compositionLines(child, depth + 1));
  if (node.kind === "content") return [`${indent}${node.name}`, ...children];
  if (children.length === 0) return [`${indent}<${node.name} />`];
  return [`${indent}<${node.name}>`, ...children, `${indent}</${node.name}>`];
}

function compositionSection(compositions: ComponentDocInput["compositions"]) {
  if (compositions.length === 0) return "";
  const examples = compositions.map((composition) =>
    [`### ${composition.title}`, composition.description ?? "", fence(compositionLines(composition.tree, 0).join("\n"), "tsx")]
      .filter(Boolean)
      .join("\n\n"),
  );
  return `## Composition\n\n${examples.join("\n\n")}`;
}

function exportsSection(modules: ComponentDocModule[]) {
  if (modules.length === 0) return "";
  const lines = modules.map((module) => {
    const names = [
      ...module.values.map((name) => `\`${name}\``),
      ...(module.types.length > 0 ? [`types ${module.types.map((name) => `\`${name}\``).join(", ")}`] : []),
    ];
    return `- \`${module.specifier}\`: ${names.join(", ")}`;
  });
  return `## Exports\n\n${lines.join("\n")}`;
}

function stateLabel(state: ContractState) {
  if (state.valueKind === "presence") return `\`${state.attribute}\``;
  if (state.valueKind === "open") return `\`${state.attribute}\` (any value)`;
  return `\`${state.attribute}\` (${state.values.map((value) => `\`${value}\``).join(" | ")})`;
}

function anatomySection(anatomy: ComponentDocInput["anatomy"]) {
  if (!anatomy) return "";
  const scopes = Object.entries(anatomy.scopes).sort(([left], [right]) => left.localeCompare(right));
  if (scopes.length === 0) return "";
  const lines = scopes.flatMap(([scopeName, scope]) => [
    `- \`${scopeName}\``,
    ...Object.entries(scope.parts)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([partName, part]) => {
        const states = part.states.length > 0 ? `: ${part.states.map(stateLabel).join(", ")}` : "";
        return `  - \`${partName}\`${states}`;
      }),
  ]);
  return `## Anatomy\n\nScopes, their parts, and the state attributes each part carries. Selector pattern: \`${anatomy.selectorPattern}\`.\n\n${lines.join("\n")}`;
}

function knobsSection(families: ComponentDocInput["knobs"]) {
  if (families.length === 0) return "";
  const groups = families.map(
    (family) => `### ${family.id}\n\n${family.knobs.map((knob) => `- \`${knob.name}\`: \`${knob.defaultValue || "(unset)"}\``).join("\n")}`,
  );
  return `## Knobs\n\nRegistered \`--cui-*\` custom properties with their recipe defaults. Set them through the component's \`style\` prop or a skin.\n\n${groups.join("\n\n")}`;
}

export function componentDocMarkdown(doc: ComponentDocInput) {
  const status = doc.status ? `\n\nStatus: ${doc.status}.` : "";
  const links = [`- Online docs (latest release): ${doc.pageUrl}`, ...doc.contractUrls.map((url) => `- Anatomy contract: ${url}`)];
  const sections = [
    generatedHeader,
    `# ${doc.name}\n\n> ${doc.summary}${status}\n\nThis file matches the installed \`${doc.id}\` source. The online docs follow the latest release and may describe a newer version.`,
    `${installSection(doc.install)}\n\n${doc.npmImportNote}`,
    ...dependencySections(doc),
    exportsSection(doc.modules),
    compositionSection(doc.compositions),
    doc.example ? `## Usage\n\n${fence(doc.example, "tsx")}` : "",
    anatomySection(doc.anatomy),
    knobsSection(doc.knobs),
    `## Links\n\n${links.join("\n")}`,
  ];
  return `${sections.filter(Boolean).join("\n\n")}\n`;
}
